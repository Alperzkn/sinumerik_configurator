"use client";

import { useEffect, useState } from "react";
import { AlertTriangle, ShieldAlert } from "lucide-react";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { cn } from "@/lib/utils";

const ACK_KEY = "sinumerik-disclaimer-ack-v1";

export function hasAcknowledgedDisclaimer(): boolean {
  if (typeof window === "undefined") return true; // SSR — don't flash
  try {
    return localStorage.getItem(ACK_KEY) !== null;
  } catch {
    return true;
  }
}

function acknowledgeDisclaimer() {
  try {
    localStorage.setItem(ACK_KEY, new Date().toISOString());
  } catch {
    /* localStorage disabled — no-op */
  }
}

interface DisclaimerDialogProps {
  open: boolean;
  /** Closing the dialog without explicit acknowledge isn't allowed by default
   *  — pass `dismissible` for the "re-read" case from the footer link. */
  dismissible?: boolean;
  onAcknowledge: () => void;
  onClose?: () => void;
}

export function DisclaimerDialog({
  open,
  dismissible = false,
  onAcknowledge,
  onClose,
}: DisclaimerDialogProps) {
  const [checked, setChecked] = useState(false);

  // Reset the checkbox each time the dialog re-opens
  useEffect(() => {
    if (open) setChecked(false);
  }, [open]);

  const handleAcknowledge = () => {
    acknowledgeDisclaimer();
    onAcknowledge();
  };

  return (
    <Dialog
      open={open}
      // Block outside-click dismissal in gating mode (base-ui prop)
      disablePointerDismissal={!dismissible}
      onOpenChange={(nextOpen) => {
        // Only allow programmatic close when dismissible. The escape key
        // / outside-click paths still call onOpenChange(false), so we
        // simply ignore them in gating mode.
        if (!nextOpen && dismissible) onClose?.();
      }}
    >
      <DialogContent
        showCloseButton={dismissible}
        className="p-0! gap-0! max-w-[min(40rem,calc(100vw-2rem))]! sm:max-w-[min(40rem,calc(100vw-2rem))]! flex flex-col overflow-hidden"
      >
        <DialogHeader className="px-6 pt-6 pb-3 border-b">
          <div className="flex items-start gap-3">
            <div className="flex h-10 w-10 items-center justify-center rounded-lg bg-amber-500/15 text-amber-500 shrink-0">
              <AlertTriangle className="h-5 w-5" strokeWidth={2} />
            </div>
            <div className="min-w-0">
              <DialogTitle className="text-base">
                Engineering review required
              </DialogTitle>
              <DialogDescription className="text-xs mt-1">
                Please read this before using the generated configuration.
              </DialogDescription>
            </div>
          </div>
        </DialogHeader>

        <div className="px-6 py-5 space-y-4 text-sm leading-relaxed">
          <p className="text-foreground">
            This configuration is generated by AI and rule-based code from a
            <span className="font-medium"> local catalog snapshot</span>. It is
            a starting point for discussion, not an order or a guarantee of
            correctness.
          </p>

          <ul className="space-y-2.5 text-[13px] text-muted-foreground">
            <li className="flex gap-2.5">
              <ShieldAlert className="h-4 w-4 mt-0.5 shrink-0 text-amber-500/80" />
              <span>
                <strong className="text-foreground">Verify every MLFB</strong>{" "}
                against your Siemens partner and the current published catalogs
                (NC63 / D21 / D31) before procurement. Article numbers, options,
                and bundle contents change between catalog releases.
              </span>
            </li>
            <li className="flex gap-2.5">
              <ShieldAlert className="h-4 w-4 mt-0.5 shrink-0 text-amber-500/80" />
              <span>
                <strong className="text-foreground">
                  Compatibility, safety integration, and motor / drive sizing
                </strong>{" "}
                must be reviewed by a qualified application engineer.
                Application-specific factors (cabling environment, EMC,
                ambient conditions, machine kinematics) are not modelled here.
              </span>
            </li>
            <li className="flex gap-2.5">
              <ShieldAlert className="h-4 w-4 mt-0.5 shrink-0 text-amber-500/80" />
              <span>
                <strong className="text-foreground">No guarantee</strong> that
                the configuration will work, satisfy any safety standard, or be
                commercially available. Use at your own risk.
              </span>
            </li>
            <li className="flex gap-2.5">
              <ShieldAlert className="h-4 w-4 mt-0.5 shrink-0 text-amber-500/80" />
              <span>
                <strong className="text-foreground">
                  Independent tool — not affiliated with Siemens AG.
                </strong>{" "}
                Use alongside your Siemens partner, not instead of one.
              </span>
            </li>
          </ul>

          <label className="flex items-start gap-3 rounded-md border border-amber-500/30 bg-amber-500/5 p-3 cursor-pointer">
            <input
              type="checkbox"
              checked={checked}
              onChange={(e) => setChecked(e.target.checked)}
              className="mt-1 h-4 w-4 cursor-pointer accent-primary"
              aria-label="I understand"
            />
            <span className="text-[13px] text-foreground select-none">
              I understand and will have this configuration reviewed by a
              qualified engineer before procurement, integration, or
              commissioning.
            </span>
          </label>
        </div>

        <div className="flex items-center justify-between gap-3 px-6 py-3 border-t bg-muted/30">
          <span className="text-[11px] text-muted-foreground">
            You won&apos;t be asked again on this device.
          </span>
          <div className="flex gap-2">
            {dismissible && (
              <Button variant="outline" size="sm" onClick={onClose}>
                Close
              </Button>
            )}
            <Button
              size="sm"
              disabled={!checked}
              onClick={handleAcknowledge}
              className={cn(!checked && "opacity-50 cursor-not-allowed")}
            >
              Acknowledge
            </Button>
          </div>
        </div>
      </DialogContent>
    </Dialog>
  );
}
