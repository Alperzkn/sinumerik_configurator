import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import type { GeneratedConfiguration, BomItem } from "@/types/catalog";

export function generatePdf(
  config: GeneratedConfiguration,
  bomLines: BomItem[]
) {
  const doc = new jsPDF();

  // Title
  doc.setFontSize(20);
  doc.setTextColor(0, 153, 153);
  doc.text("SINUMERIK ONE", 14, 22);
  doc.setFontSize(14);
  doc.setTextColor(100, 100, 100);
  doc.text("Configuration - Bill of Materials", 14, 30);

  // Summary
  doc.setFontSize(10);
  doc.setTextColor(60, 60, 60);
  const y = 40;
  doc.text(
    `Control Unit: ${config.controlUnit.name} (${config.controlUnit.articleNumber})`,
    14, y
  );
  doc.text(
    `CNC Software: ${config.softwareVariant === "export" ? "Export" : "Full Scope"} - SW ${config.cncSoftware.swVersion}`,
    14, y + 6
  );
  doc.text(
    `Total Axes: ${config.totalAxes} | Channels: ${config.totalChannels} | Complexity: ${config.estimatedComplexity}`,
    14, y + 12
  );
  doc.text(`Generated: ${new Date().toLocaleDateString()}`, 14, y + 18);

  // BOM Table
  const tableData = bomLines.map((line, i) => [
    (i + 1).toString(),
    line.articleNumber,
    line.quantity.toString(),
    `${line.name}${line.orderCode ? ` (${line.orderCode})` : ""}`,
    line.category,
  ]);

  autoTable(doc, {
    startY: y + 26,
    head: [["#", "MLFB / Article No.", "Qty", "Description", "Category"]],
    body: tableData,
    styles: { fontSize: 7.5, cellPadding: 2.5 },
    headStyles: {
      fillColor: [0, 153, 153],
      textColor: [255, 255, 255],
      fontStyle: "bold",
    },
    alternateRowStyles: { fillColor: [245, 245, 245] },
    columnStyles: {
      0: { cellWidth: 10, halign: "center" },
      1: { cellWidth: 42, font: "courier" },
      2: { cellWidth: 10, halign: "center" },
      3: { cellWidth: "auto" },
      4: { cellWidth: 28 },
    },
  });

  // Notes
  if (config.notes.length > 0) {
    const finalY = (doc as jsPDF & { lastAutoTable: { finalY: number } })
      .lastAutoTable.finalY;
    doc.setFontSize(9);
    doc.setTextColor(100, 100, 100);
    doc.text("Notes:", 14, finalY + 10);
    config.notes.forEach((note, i) => {
      doc.text(`- ${note}`, 16, finalY + 16 + i * 5);
    });
  }

  // Footer
  const pageHeight = doc.internal.pageSize.height;
  doc.setFontSize(7);
  doc.setTextColor(150, 150, 150);
  doc.text(
    "Generated by SINUMERIK ONE Configurator | Based on NC63 Catalog January 2026",
    14,
    pageHeight - 10
  );

  doc.save("sinumerik-one-configuration.pdf");
}
