import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import type { GeneratedConfiguration, BomItem, MachineType } from "@/types/catalog";
import type { MachineSpecsState } from "@/store/configurator-store";

/**
 * Optional user-input context passed in from the configurator store.
 * Used to compose a deterministic narrative on the rationale page —
 * NEVER send any value through an LLM here; everything is verbatim
 * from the user's own answers.
 */
export interface PdfUserContext {
  template: MachineType | null;
  description: string;
  specs: MachineSpecsState;
}

/** Page-layout constants used across helpers. */
const LEFT = 14;
const TEXT_WIDTH = 180; // A4 width 210mm − ~30mm side margins.
const LINE_H = 4.2;

export function generatePdf(
  config: GeneratedConfiguration,
  bomLines: BomItem[],
  userContext?: PdfUserContext,
) {
  const doc = new jsPDF();

  // ── Title ──────────────────────────────────────────────────────────
  doc.setFontSize(20);
  doc.setTextColor(0, 153, 153);
  doc.text("SINUMERIK ONE", LEFT, 22);
  doc.setFontSize(14);
  doc.setTextColor(100, 100, 100);
  doc.text("Configuration · Bill of Materials", LEFT, 30);

  // ── Summary ────────────────────────────────────────────────────────
  doc.setFontSize(10);
  doc.setTextColor(60, 60, 60);
  const y = 40;
  doc.text(
    `Control Unit: ${config.controlUnit.name} (${config.controlUnit.articleNumber})`,
    LEFT, y
  );
  doc.text(
    `CNC Software: ${config.softwareVariant === "export" ? "Export" : "Full Scope"} · SW ${config.cncSoftware.swVersion}`,
    LEFT, y + 6
  );
  doc.text(
    `Total Axes: ${config.totalAxes} | Channels: ${config.totalChannels} | Complexity: ${config.estimatedComplexity}`,
    LEFT, y + 12
  );
  doc.text(`Generated: ${new Date().toLocaleDateString()}`, LEFT, y + 18);

  // ── BOM Table ──────────────────────────────────────────────────────
  const tableData = bomLines.map((line, i) => [
    (i + 1).toString(),
    line.articleNumber,
    line.quantity.toString(),
    `${line.name}${line.orderCode ? ` (${line.orderCode})` : ""}`,
    line.category,
  ]);

  autoTable(doc, {
    startY: y + 26,
    head: [["#", "MLFB / Article No.", "Qty", "Description", "Category"]],
    body: tableData,
    styles: { fontSize: 7.5, cellPadding: 2.5 },
    headStyles: {
      fillColor: [0, 153, 153],
      textColor: [255, 255, 255],
      fontStyle: "bold",
    },
    alternateRowStyles: { fillColor: [245, 245, 245] },
    columnStyles: {
      0: { cellWidth: 10, halign: "center" },
      1: { cellWidth: 42, font: "courier" },
      2: { cellWidth: 10, halign: "center" },
      3: { cellWidth: "auto" },
      4: { cellWidth: 28 },
    },
  });

  // ── Notes (wrapping fixed) ─────────────────────────────────────────
  // Long notes were previously truncated at the right margin because
  // doc.text was called without a maxWidth and stepped a fixed 5mm
  // per item. Now each note wraps into multiple lines and the cursor
  // advances by the actual line count.
  if (config.notes.length > 0) {
    const finalY = (doc as jsPDF & { lastAutoTable: { finalY: number } })
      .lastAutoTable.finalY;
    doc.setFontSize(9);
    doc.setTextColor(100, 100, 100);
    doc.text("Notes:", LEFT, finalY + 10);
    let noteY = finalY + 16;
    for (const note of config.notes) {
      const wrapped = doc.splitTextToSize(`- ${note}`, TEXT_WIDTH - 4);
      doc.text(wrapped, LEFT + 2, noteY);
      noteY += wrapped.length * LINE_H + 1.5;
    }
  }

  // ── Configuration Rationale (new page) ─────────────────────────────
  // Per-axis MLFB breakdown + every component's reasoning so the user
  // (and their Siemens partner) can audit every decision.
  appendRationale(doc, config, userContext);

  // ── Footer (final page) ────────────────────────────────────────────
  const pageHeight = doc.internal.pageSize.height;
  doc.setFontSize(7);
  doc.setTextColor(150, 150, 150);
  doc.text(
    "Generated by SINUMERIK ONE Configurator | Based on Siemens NC63, D21, D31 catalogs — 2026 scope",
    LEFT,
    pageHeight - 10
  );

  doc.save("sinumerik-one-configuration.pdf");
}

/**
 * Append a "Configuration Rationale" page that documents WHY each
 * choice was made and what every MLFB suffix means. This is the
 * verify-with-Siemens output: a partner can read it row-by-row and
 * confirm the configuration without going back to the conversation.
 */
function appendRationale(
  doc: jsPDF,
  config: GeneratedConfiguration,
  ctx?: PdfUserContext,
) {
  doc.addPage();
  let cursor = 20;

  doc.setFontSize(16);
  doc.setTextColor(0, 153, 153);
  doc.text("Configuration Rationale", LEFT, cursor);
  cursor += 8;

  doc.setFontSize(8);
  doc.setTextColor(120, 120, 120);
  doc.text(
    "Why each component was selected, with per-axis MLFB suffix decoding so you can verify every order code.",
    LEFT,
    cursor,
    { maxWidth: TEXT_WIDTH },
  );
  cursor += 10;

  // ── Configuration overview (narrative) ────────────────────────────
  // Composed deterministically from the user's own inputs — never
  // through an LLM. Renders only when context was passed in.
  if (ctx) {
    cursor = ensureSpace(doc, cursor, 60);
    doc.setFontSize(11);
    doc.setTextColor(0, 0, 0);
    doc.text("Configuration overview", LEFT, cursor);
    cursor += 5;

    const overview = composeOverview(config, ctx);
    doc.setFontSize(9);
    doc.setTextColor(60, 60, 60);
    const lines = doc.splitTextToSize(overview, TEXT_WIDTH);
    doc.text(lines, LEFT, cursor);
    cursor += lines.length * LINE_H + 4;

    // Original requirements — verbatim from the user's description
    // box (if any) and key spec inputs. Helps reviewers see what was
    // asked vs. what was delivered.
    if (ctx.description.trim()) {
      cursor = ensureSpace(doc, cursor, 30);
      doc.setFontSize(9);
      doc.setTextColor(120, 120, 120);
      doc.text("Original requirement (verbatim):", LEFT, cursor);
      cursor += 4;
      doc.setTextColor(60, 60, 60);
      const desc = doc.splitTextToSize(`"${ctx.description.trim()}"`, TEXT_WIDTH);
      doc.text(desc, LEFT, cursor);
      cursor += desc.length * LINE_H + 4;
    }

    const specRows = inputSpecRows(ctx.specs);
    if (specRows.length > 0) {
      cursor = ensureSpace(doc, cursor, 40);
      autoTable(doc, {
        startY: cursor,
        head: [["Input parameter", "Value"]],
        body: specRows,
        styles: { fontSize: 8, cellPadding: 2 },
        headStyles: { fillColor: [200, 200, 200], textColor: [0, 0, 0], fontStyle: "bold" },
        columnStyles: {
          0: { cellWidth: 60, fontStyle: "bold" },
          1: { cellWidth: "auto" },
        },
      });
      cursor = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 8;
    }
  }

  // ── Architecture decisions ────────────────────────────────────────
  cursor = ensureSpace(doc, cursor, 50);
  doc.setFontSize(11);
  doc.setTextColor(0, 0, 0);
  doc.text("Architecture decisions", LEFT, cursor);
  cursor += 5;

  const archRows: string[][] = [
    [
      "Control Unit",
      `${config.controlUnit.name} — ${controlUnitRationale(config)}`,
      config.controlUnit.articleNumber || "—",
    ],
    [
      "CNC Software",
      `${config.softwareVariant === "export" ? "Export" : "Full Scope"} · SW ${config.cncSoftware.swVersion} — ${cncSoftwareRationale(config)}`,
      config.cncSoftware.articleNumber || "—",
    ],
    ["Total axes", String(config.totalAxes), ""],
    ["Channels", String(config.totalChannels), ""],
    ["Complexity tier", config.estimatedComplexity, ""],
  ];

  autoTable(doc, {
    startY: cursor,
    head: [["Architecture", "Choice & rationale", "Article No."]],
    body: archRows,
    styles: { fontSize: 8, cellPadding: 2 },
    headStyles: { fillColor: [0, 153, 153], textColor: [255, 255, 255], fontStyle: "bold" },
    columnStyles: {
      0: { cellWidth: 38, fontStyle: "bold" },
      1: { cellWidth: "auto" },
      2: { cellWidth: 42, font: "courier" },
    },
  });
  cursor = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 8;

  // ── Selected packages & options ────────────────────────────────────
  // Each row's "Selected for" comes from the catalog description field
  // — never AI-generated, so the partner can compare against the
  // ordering catalog directly.
  const selectionRows: string[][] = [];
  for (const pkg of config.technologyPackages) {
    selectionRows.push([
      "Tech package",
      pkg.orderCode || "—",
      pkg.name,
      pkg.description || "—",
      pkg.articleNumber || "—",
    ]);
  }
  for (const opt of config.softwareOptions) {
    const qty = config.optionQuantities[opt.id] || 1;
    selectionRows.push([
      `Option${qty > 1 ? ` × ${qty}` : ""}`,
      opt.orderCode || "—",
      opt.name,
      opt.description || "—",
      opt.articleNumber || "—",
    ]);
  }
  if (selectionRows.length > 0) {
    cursor = ensureSpace(doc, cursor, 40);
    doc.setFontSize(11);
    doc.setTextColor(0, 0, 0);
    doc.text("Selected packages & software options", LEFT, cursor);
    cursor += 5;
    autoTable(doc, {
      startY: cursor,
      head: [["Type", "Order code", "Name", "Selected for", "Article No."]],
      body: selectionRows,
      styles: { fontSize: 7.5, cellPadding: 2 },
      headStyles: { fillColor: [0, 153, 153], textColor: [255, 255, 255], fontStyle: "bold" },
      columnStyles: {
        0: { cellWidth: 22 },
        1: { cellWidth: 22, font: "courier" },
        2: { cellWidth: 40 },
        3: { cellWidth: "auto" },
        4: { cellWidth: 38, font: "courier" },
      },
    });
    cursor = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 8;
  }

  // ── Drive & motor rationale (one-liners) ──────────────────────────
  const driveLines = driveSystemRationale(config);
  if (driveLines.length > 0) {
    cursor = ensureSpace(doc, cursor, 12 + driveLines.length * 5);
    doc.setFontSize(11);
    doc.setTextColor(0, 0, 0);
    doc.text("Drive & motor rationale", LEFT, cursor);
    cursor += 5;
    doc.setFontSize(9);
    doc.setTextColor(60, 60, 60);
    for (const line of driveLines) {
      const wrapped = doc.splitTextToSize(`- ${line}`, TEXT_WIDTH - 4);
      cursor = ensureSpace(doc, cursor, wrapped.length * LINE_H + 2);
      doc.text(wrapped, LEFT + 2, cursor);
      cursor += wrapped.length * LINE_H + 1.5;
    }
    cursor += 4;
  }

  // ── Per-axis MLFB breakdown ────────────────────────────────────────
  for (const motor of config.motors) {
    if (!motor.perAxisMlfbs || motor.perAxisMlfbs.length === 0) continue;
    cursor = ensureSpace(doc, cursor, 30);

    doc.setFontSize(11);
    doc.setTextColor(0, 0, 0);
    doc.text(`Per-axis MLFB · ${motor.name}`, LEFT, cursor);
    cursor += 5;
    doc.setFontSize(8);
    doc.setTextColor(120, 120, 120);
    doc.text(
      "Each axis carries its own orderable MLFB. The suffix encodes the axis's specific options (encoder, brake, shaft form).",
      LEFT,
      cursor,
      { maxWidth: TEXT_WIDTH },
    );
    cursor += 6;

    const axisRows = motor.perAxisMlfbs.map((a) => [
      a.axis,
      a.mlfb,
      a.brake ? "yes" : "no",
      (a.decoded ?? [])
        .map((d) => `${d.label}: ${d.choiceLabel} (${d.code})`)
        .join(" · "),
    ]);

    autoTable(doc, {
      startY: cursor,
      head: [["Axis", "Full MLFB", "Brake", "Suffix decoder"]],
      body: axisRows,
      styles: { fontSize: 7.5, cellPadding: 2 },
      headStyles: { fillColor: [0, 153, 153], textColor: [255, 255, 255], fontStyle: "bold" },
      columnStyles: {
        0: { cellWidth: 14, fontStyle: "bold" },
        1: { cellWidth: 42, font: "courier" },
        2: { cellWidth: 14, halign: "center" },
        3: { cellWidth: "auto" },
      },
    });
    cursor = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 8;
  }

  // ── Warnings ──────────────────────────────────────────────────────
  if (config.warnings.length > 0) {
    cursor = ensureSpace(doc, cursor, 30);
    doc.setFontSize(11);
    doc.setTextColor(0, 0, 0);
    doc.text("Warnings", LEFT, cursor);
    cursor += 6;
    autoTable(doc, {
      startY: cursor,
      head: [["Severity", "Message"]],
      body: config.warnings.map((w) => [w.severity, w.message]),
      styles: { fontSize: 7.5, cellPadding: 2 },
      headStyles: { fillColor: [220, 100, 0], textColor: [255, 255, 255], fontStyle: "bold" },
      columnStyles: {
        0: { cellWidth: 22, halign: "center" },
        1: { cellWidth: "auto" },
      },
    });
    cursor = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 8;
  }

  // ── Disclaimer ────────────────────────────────────────────────────
  cursor = ensureSpace(doc, cursor, 20);
  doc.setFontSize(7);
  doc.setTextColor(150, 150, 150);
  doc.text(
    "This rationale is generated from the AI-assisted configurator. Verify every MLFB with your Siemens partner before procurement. " +
      "Article numbers, options, and bundle contents change between catalog releases (NC63, D21.4, D31, D32).",
    LEFT,
    cursor,
    { maxWidth: TEXT_WIDTH },
  );
}

// ─── Helpers ──────────────────────────────────────────────────────────

/** Push a fresh page if `cursor` is too low to fit `needed` mm. */
function ensureSpace(doc: jsPDF, cursor: number, needed: number): number {
  const pageHeight = doc.internal.pageSize.height;
  if (cursor + needed > pageHeight - 18) {
    doc.addPage();
    return 20;
  }
  return cursor;
}

const TEMPLATE_LABEL: Record<MachineType, string> = {
  "3axis_mill": "3-axis milling machine",
  "5axis_mill": "5-axis milling machine",
  cnc_lathe: "CNC lathe",
  mill_turn: "Mill-turn machining centre",
  grinding: "Grinding machine",
  laser: "Laser machining system",
  punching: "Punching / nibbling machine",
  robot: "Robot motion controller",
  custom: "Custom machine",
};

/**
 * Compose a deterministic narrative paragraph from the configuration.
 * Pulls verbatim from `config` and `ctx.specs` — no LLM, no
 * fabricated detail.
 */
function composeOverview(config: GeneratedConfiguration, ctx: PdfUserContext): string {
  const sentences: string[] = [];
  const machineLabel = ctx.template ? TEMPLATE_LABEL[ctx.template] : "CNC machine";
  const channelWord = config.totalChannels === 1 ? "channel" : "channels";
  sentences.push(
    `${machineLabel} configuration with ${config.totalAxes} axes across ${config.totalChannels} ${channelWord}.`,
  );

  const specHints: string[] = [];
  const s = ctx.specs;
  if (s.spindlePower) specHints.push(`spindle ${s.spindlePower}`);
  if (s.spindleSpeed) specHints.push(`up to ${s.spindleSpeed}`);
  if (s.rapidTraverse) specHints.push(`rapid ${s.rapidTraverse}`);
  if (s.movingMass) specHints.push(`moving mass ${s.movingMass}`);
  if (specHints.length > 0) {
    sentences.push(`Sized for ${specHints.join(", ")}.`);
  }

  const contextHints: string[] = [];
  if (s.material) contextHints.push(`material: ${s.material}`);
  if (s.machineSize) contextHints.push(`size: ${s.machineSize}`);
  if (s.safetyLevel) contextHints.push(`safety: ${s.safetyLevel}`);
  if (contextHints.length > 0) {
    sentences.push(`Working envelope — ${contextHints.join("; ")}.`);
  }

  sentences.push(
    `Engine reports ${config.estimatedComplexity} complexity tier; ${config.technologyPackages.length} technology package(s) and ${config.softwareOptions.length} software option(s) selected.`,
  );

  return sentences.join(" ");
}

/** Tabular view of the user's own input parameters — shown verbatim. */
function inputSpecRows(s: MachineSpecsState): string[][] {
  const rows: string[][] = [];
  const push = (label: string, value: string) => {
    if (value && value.trim()) rows.push([label, value]);
  };
  push("Spindle power", s.spindlePower);
  push("Spindle speed", s.spindleSpeed);
  push("Rapid traverse", s.rapidTraverse);
  push("Moving mass", s.movingMass);
  push("Axis travel", s.axisTravel);
  push("Material", s.material);
  push("Machine size", s.machineSize);
  push("Safety level", s.safetyLevel);
  push("Cable length", s.cableLengthMeters ? `${s.cableLengthMeters} m` : "");
  push("Handheld unit", s.handheldUnit);
  push("I/O module", s.ioModule);
  return rows;
}

/** Short, factual rationale for the chosen control unit. */
function controlUnitRationale(config: GeneratedConfiguration): string {
  const cu = config.controlUnit;
  const usage = `${config.totalAxes}/${cu.maxAxesSpindles} axes, ${config.totalChannels}/${cu.maxChannels} channels in use`;
  const formFactor =
    cu.formFactor === "panel_based"
      ? "panel-based unit with built-in HMI"
      : "cabinet-based unit (separate operator panel)";
  return `${formFactor}; ${usage}`;
}

/** Short, factual rationale for the CNC software variant. */
function cncSoftwareRationale(config: GeneratedConfiguration): string {
  return config.softwareVariant === "export"
    ? "export variant — restricted scope for export-controlled territories"
    : "full scope — unrestricted feature set";
}

/** Compose one-line rationale per drive/motor architectural choice. */
function driveSystemRationale(config: GeneratedConfiguration): string[] {
  const lines: string[] = [];
  for (const drive of config.drives) {
    if (drive.componentType === "line_module_active") {
      lines.push(
        `${drive.name} — Active Line Module: regenerative feedback to grid, sinusoidal currents (recommended for high duty cycles).`,
      );
    } else if (drive.componentType === "line_module_smart") {
      lines.push(
        `${drive.name} — Smart Line Module: regenerative feedback to grid (lower-cost alternative to ALM for moderate duty).`,
      );
    } else if (drive.componentType === "line_module_basic") {
      lines.push(
        `${drive.name} — Basic Line Module: non-regenerative; surplus energy dissipated in braking resistor.`,
      );
    }
  }

  for (const motor of config.motors) {
    if (motor.motorType === "feed_servo_sync") {
      lines.push(
        `${motor.name} (${motor.series}) — synchronous servo for feed axes; matched to the per-axis sizing pass.`,
      );
    } else if (motor.motorType === "main_spindle_async") {
      lines.push(
        `${motor.name} (${motor.series}) — asynchronous main spindle; broad constant-power range, suitable for heavy machining.`,
      );
    } else if (motor.motorType === "main_spindle_sync") {
      lines.push(
        `${motor.name} (${motor.series}) — synchronous main spindle; high dynamic response for HSC and milling spindles.`,
      );
    }
  }

  return lines;
}
